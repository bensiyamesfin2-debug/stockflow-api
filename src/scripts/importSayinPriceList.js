const PRICE_LIST_NAME = "Sayin Granite Price List";

async function importSayinPriceList() {
  const admin = await prisma.user.findFirst({ where: { role: "ADMIN" }, orderBy: { id: "asc" } });
  if (!admin) throw new Error("No ADMIN user exists yet -- create one first (see src/scripts/createAdmin.js)");

  const priceList = await prisma.$transaction(async (transaction) => {
    const existing = await transaction.priceList.findUnique({ where: { name: PRICE_LIST_NAME } });
    const list = existing
      ? existing
      : await transaction.priceList.create({
          data: { name: PRICE_LIST_NAME, description: "Imported from Sayin Granite Importer's price sheet", createdById: admin.id },
        });

    let matched = 0;
    let created = 0;
    for (const item of PRICE_LIST_ITEMS) {
      const normalized = normalizeProductName(item.name);
      const name = normalized.error ? item.name : normalized.name;
      let product = await transaction.product.findFirst({
        where: { name, length: item.length, width: item.width, thickness: item.thickness },
      });
      if (!product) {
        product = await transaction.product.create({
          data: {
            sku: makeInternalSku(name, item.length, item.width, item.thickness),
            name,
            length: item.length,
            width: item.width,
            thickness: item.thickness,
            sellingPrice: item.price,
            inventory: { create: { quantity: 0, reorderLevel: 5 } },
          },
        });
        created += 1;
      } else {
        matched += 1;
      }
      await transaction.priceListItem.upsert({
        where: { priceListId_productId: { priceListId: list.id, productId: product.id } },
        update: { price: item.price },
        create: { priceListId: list.id, productId: product.id, price: item.price },
      });
    }

    await transaction.auditLog.create({
      data: {
        userId: admin.id,
        action: "IMPORT_SAYIN_PRICE_LIST",
        entityType: "PRICE_LIST",
        entityId: list.id,
        details: { itemsSet: PRICE_LIST_ITEMS.length, existingProductsMatched: matched, newZeroStockProductsCreated: created },
      },
    });
    return { list, matched, created };
  }, { timeout: 60_000 });

  console.log(JSON.stringify({
    status: "Sayin Granite price list imported",
    priceListId: priceList.list.id,
    priceListName: priceList.list.name,
    itemsSet: PRICE_LIST_ITEMS.length,
    existingProductsMatched: priceList.matched,
    newZeroStockProductsCreated: priceList.created,
  }, null, 2));
}

if (require.main === module) {
  importSayinPriceList()
    .catch((error) => {
      console.error(`Unable to import the Sayin price list: ${error.message}`);
      process.exitCode = 1;
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}

module.exports = { importSayinPriceList, PRICE_LIST_ITEMS, PRICE_LIST_NAME };
